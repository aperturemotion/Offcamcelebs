# -*- coding: utf-8 -*-
# Measures the cut-out (029: assets/mayweather_final.png; 028: kim_final.png) and writes src/audit/photo.ts: the image size, the head's centre x and the
# hair's top, where a crown SEATS (the row where the head is ~400 px wide), and the face circle for the avatar token; plus
# the silhouette as 14 horizontal BANDS (each band's alpha extent), which the film draws as invisible measured boxes so the
# probe judges her shape, not her square image box. Never guessed: every number is read off the alpha.
#   python scratchpad/photobox.py
import numpy as np, sys
from PIL import Image
sys.stdout.reconfigure(encoding="utf-8")
SRC = "assets/danawhite_sharp.png"   # ★ 033: the ×2 defringed, sharpened cut-out with its foot and sides faded (dwsharp.py)
im = Image.open(SRC).convert("RGBA")
a = np.asarray(im)[..., 3] > 128
H, W = a.shape
# ★ 031: his hair's top is wisps, so a stray strand is not the head's top: the first row ≥ 20 px opaque is
rows = np.where(a.sum(axis=1) >= 20)[0]
top = int(rows[0])
def ext(y):
    xs = np.where(a[y])[0]
    if len(xs) == 0: xs = np.where(a[max(top, y - 6):y + 7].any(axis=0))[0]   # a row between two wisps: its neighbours'
    return int(xs[0]), int(xs[-1])
# the head's centre: the hair's mid-x over its first 200 rows
cx = int(round(np.mean([sum(ext(y)) / 2 for y in range(top + 10, top + 200, 10)])))
# where a crown seats: the first row whose width reaches 0.72 of the head's widest (hair) width over rows top..top+300
widest = max(ext(y)[1] - ext(y)[0] for y in range(top, top + 300))
seat = next(y for y in range(top, top + 300) if ext(y)[1] - ext(y)[0] >= 0.72 * widest)
crownW = int(round(0.78 * (ext(seat)[1] - ext(seat)[0])))
# the face circle: centred between the hair top and the chin line (row where the width narrows below the jaw)
# ★ 028: the face circle is measured off the FACE, not as a share of the image. (027's formula assumed a square bust; on
#   this tall portrait it put the token's centre on her forehead and its radius at the whole head.) The hairline is the
#   first row with a run of skin across the middle half; the chin is read off the photo at 1:1 (source row 435, ×2), since
#   her neck is skin too and the skin profile shows no edge there. The centre x is the skin's centroid between the two.
# ★ 029 (his photo, 800 × 800): 028's skin thresholds were tuned on one complexion and are not used. His head is bald, so
#   the head's TOP is read off the alpha (the first opaque row), and the chin off the photo at 1:1 (row 345, below his
#   beard, which the alpha cannot show). The centre x is the head's own: the middle of its outline at rows 40–200.
# ★ 030 (his photo, 612 × 637 after the crop): the head's top is his hair's (the first opaque row); the chin is the beard's
#   bottom, read at 1:1 on the source (row 285).
# ★ 031 (his photo, 700 × 816): the chin is the shadow under it, read at 1:1 on the source (the darkest row of the face's
#   centre columns below the mouth: row 424)
# ★ 032 (his photo, 520 × 325): the chin is the beard's bottom, read at 1:1 on the source (row 180, where the outline
#   stops narrowing under the jaw and the neck begins)
CHIN = round(345 * H / 900)        # ★ 033 (his photo, 900 × 900): the chin, read at 1:1 on the source (row 345, under the jaw's shadow)
head_top = top
if not (head_top + 250 < CHIN < H): sys.exit(f"REFUSING — head top {head_top} and chin {CHIN} do not make a face")
hc = int(round(np.mean([sum(ext(y)) / 2 for y in range(head_top + 40, head_top + 200, 10)])))
face = {"cx": hc, "cy": (head_top + CHIN) // 2, "r": int(0.56 * (CHIN - head_top))}
n = 14
edges = np.linspace(top, H, n + 1).astype(int)
bands = []
for y0, y1 in zip(edges[:-1], edges[1:]):
    sub = a[y0:y1]
    cols = np.where(sub.any(axis=0))[0]
    if len(cols): bands.append([int(y0), int(y1), int(cols[0]), int(cols[-1]) + 1])
assert len(bands) >= 10, "too few bands"
out = (
    f"// GENERATED by scratchpad/photobox.py from {SRC} — do not hand-edit; re-run it.\n"
    "// Image px. `seat`: the row a crown's band bottom rests on; `crownW`: its width there. `bands`: the silhouette, row band\n"
    "// by row band [y0, y1, x0, x1], drawn as invisible measured boxes for the probe.\n"
    f"export const PHOTO = {{ w: {W}, h: {H}, cx: {cx}, top: {top}, seat: {seat}, crownW: {crownW}, face: {{ cx: {face['cx']}, cy: {face['cy']}, r: {face['r']} }},\n"
    f"  bands: {bands} }} as const;\n"
)
open("src/audit/photo.ts", "w", encoding="utf8").write(out)
print(f"head cx {cx}, top {top}, seat {seat} (width {ext(seat)[1] - ext(seat)[0]}), crownW {crownW}, face {face}, {len(bands)} bands")
